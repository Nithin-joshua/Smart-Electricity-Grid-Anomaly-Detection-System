# ==============================================================================
# FILE: model/training/dataset_loader.py
# PURPOSE: Memory-efficient Parquet dataset loading for the training pipeline.
#          Loads per-meter Parquet files with validation, filtering, and
#          generator-based iteration to avoid loading 25M+ rows at once.
# ==============================================================================

"""
Dataset Loader
----------------
Provides file-level I/O and validation for the per-meter Parquet datasets
generated by the Milestone 2 Parquet dataset generator.

Design decisions:
- **Generator pattern**: The `iter_meter_dataframes()` method yields one
  DataFrame at a time, keeping peak memory usage proportional to a single
  meter's data (~20MB) rather than the full fleet (~1GB).
- **Schema validation**: Every loaded DataFrame is validated for expected
  columns, data types, and NaN presence before being passed downstream.
  This catches corruption early rather than during model.fit().
- **Sorted output**: DataFrames are sorted by timestamp to ensure temporal
  ordering for correct sliding window extraction.
"""

import os
import glob
from typing import List, Generator, Optional

import numpy as np
import pandas as pd

import sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from config.training_config import (
    NORMAL_DATA_OUTPUT_DIR,
    TRAINING_FEATURE_COLUMNS,
)
from utils.logging_setup import get_module_logger

# Module-scoped logger for dataset loading operations.
loader_logger = get_module_logger("dataset_loader")

# Expected columns in each Parquet file — must match the generator output.
REQUIRED_PARQUET_COLUMNS: List[str] = [
    "meter_id", "timestamp", "kwh", "voltage", "current", "seq_no"
]


def discover_parquet_files(data_directory: str) -> List[str]:
    """
    Find all Parquet files in the specified data directory.

    Uses glob pattern matching to locate files named `meter_*.parquet`.
    Results are sorted alphabetically for deterministic iteration order.

    Args:
        data_directory: Absolute or relative path to the data directory.

    Returns:
        Sorted list of absolute file paths to discovered Parquet files.

    Raises:
        FileNotFoundError: If the data directory doesn't exist.
        ValueError: If no Parquet files are found.
    """
    if not os.path.isdir(data_directory):
        raise FileNotFoundError(
            f"Data directory does not exist: {data_directory}. "
            f"Run the Parquet dataset generator first: "
            f"python -m simulator.parquet_dataset_generator --meters 50 --days 30"
        )

    # Match the naming convention from parquet_dataset_generator.py.
    search_pattern: str = os.path.join(data_directory, "meter_*.parquet")
    parquet_file_paths: List[str] = sorted(glob.glob(search_pattern))

    if not parquet_file_paths:
        raise ValueError(
            f"No Parquet files matching 'meter_*.parquet' found in: "
            f"{data_directory}. Run the dataset generator first."
        )

    loader_logger.info(
        "Discovered %d Parquet files in %s",
        len(parquet_file_paths),
        data_directory,
    )

    return parquet_file_paths


def validate_meter_dataframe(
    meter_df: pd.DataFrame,
    source_file: str,
) -> pd.DataFrame:
    """
    Validate a loaded meter DataFrame for schema and data integrity.

    Checks performed:
    1. All required columns are present.
    2. Feature columns contain no NaN values.
    3. Feature columns are numeric (float64 or int64).
    4. DataFrame has at least 1 row.

    If NaN values are found, they are forward-filled (common for
    minor Parquet corruption) and a warning is logged. If >5% of rows
    contain NaNs, the file is rejected entirely.

    Args:
        meter_df: The loaded DataFrame to validate.
        source_file: Path to the source Parquet file (for error messages).

    Returns:
        The validated (and possibly cleaned) DataFrame.

    Raises:
        ValueError: If the DataFrame fails critical validation checks.
    """
    # Check 1: Non-empty DataFrame.
    if meter_df.empty:
        raise ValueError(
            f"Empty DataFrame loaded from {source_file}. "
            f"The file may be corrupted or contain no data."
        )

    # Check 2: Required columns exist.
    missing_columns: set = set(REQUIRED_PARQUET_COLUMNS) - set(meter_df.columns)
    if missing_columns:
        raise ValueError(
            f"Missing required columns in {source_file}: {missing_columns}. "
            f"Expected columns: {REQUIRED_PARQUET_COLUMNS}. "
            f"Found columns: {list(meter_df.columns)}"
        )

    # Check 3: Feature columns are numeric.
    for feature_col in TRAINING_FEATURE_COLUMNS:
        if not np.issubdtype(meter_df[feature_col].dtype, np.number):
            raise ValueError(
                f"Feature column '{feature_col}' in {source_file} is not numeric. "
                f"Dtype: {meter_df[feature_col].dtype}. Expected float64 or int64."
            )

    # Check 4: Handle NaN values in feature columns.
    nan_counts: pd.Series = meter_df[TRAINING_FEATURE_COLUMNS].isna().sum()
    total_nans: int = int(nan_counts.sum())

    if total_nans > 0:
        nan_ratio: float = total_nans / (len(meter_df) * len(TRAINING_FEATURE_COLUMNS))

        if nan_ratio > 0.05:
            raise ValueError(
                f"Excessive NaN values in {source_file}: "
                f"{total_nans} NaNs across {len(meter_df)} rows "
                f"({nan_ratio:.1%} of values). File may be corrupted."
            )

        # Forward-fill minor NaN occurrences (e.g., from Parquet write interruption).
        loader_logger.warning(
            "Found %d NaN values in %s (%.2f%%) — applying forward-fill",
            total_nans,
            source_file,
            nan_ratio * 100,
        )
        meter_df[TRAINING_FEATURE_COLUMNS] = meter_df[TRAINING_FEATURE_COLUMNS].ffill()

        # If any NaNs remain after ffill (at the start of the series), backfill.
        meter_df[TRAINING_FEATURE_COLUMNS] = meter_df[TRAINING_FEATURE_COLUMNS].bfill()

    return meter_df


def load_single_meter_parquet(parquet_file_path: str) -> pd.DataFrame:
    """
    Load and validate a single meter's Parquet file.

    Reads the Parquet file, validates its schema, sorts by timestamp
    to ensure temporal ordering, and returns the cleaned DataFrame.

    Args:
        parquet_file_path: Absolute path to the Parquet file.

    Returns:
        Validated DataFrame sorted by timestamp.

    Raises:
        FileNotFoundError: If the file doesn't exist.
        ValueError: If the file fails validation.
    """
    if not os.path.isfile(parquet_file_path):
        raise FileNotFoundError(
            f"Parquet file not found: {parquet_file_path}"
        )

    try:
        meter_df: pd.DataFrame = pd.read_parquet(
            parquet_file_path,
            engine="pyarrow",
        )
    except Exception as read_error:
        raise ValueError(
            f"Failed to read Parquet file {parquet_file_path}: {read_error}"
        ) from read_error

    # Validate schema and data integrity.
    meter_df = validate_meter_dataframe(meter_df, parquet_file_path)

    # Sort by timestamp for correct temporal ordering.
    # The generator produces data in order, but sorting guards against
    # files that were manually edited or appended out of order.
    meter_df = meter_df.sort_values("timestamp").reset_index(drop=True)

    loader_logger.debug(
        "Loaded %s | rows=%d | columns=%s",
        os.path.basename(parquet_file_path),
        len(meter_df),
        list(meter_df.columns),
    )

    return meter_df


def iter_meter_dataframes(
    data_directory: str = NORMAL_DATA_OUTPUT_DIR,
    max_meters: Optional[int] = None,
) -> Generator[pd.DataFrame, None, None]:
    """
    Yield one validated DataFrame per meter from the data directory.

    This is the primary data loading interface for the training pipeline.
    It uses a generator pattern to keep memory usage proportional to a
    single meter's data (~20MB), not the full fleet (~1GB).

    Args:
        data_directory: Path to the directory containing Parquet files.
        max_meters: Optional limit on the number of meters to load.
                    Useful for debugging (e.g., max_meters=3 for quick tests).

    Yields:
        One DataFrame per meter, validated and sorted by timestamp.
    """
    parquet_files: List[str] = discover_parquet_files(data_directory)

    # Apply optional meter limit.
    if max_meters is not None and max_meters > 0:
        parquet_files = parquet_files[:max_meters]
        loader_logger.info(
            "Limiting to first %d meters (of %d discovered)",
            max_meters,
            len(parquet_files),
        )

    for file_path in parquet_files:
        yield load_single_meter_parquet(file_path)


def load_all_feature_arrays(
    data_directory: str = NORMAL_DATA_OUTPUT_DIR,
    max_meters: Optional[int] = None,
) -> np.ndarray:
    """
    Load and concatenate feature arrays from all meters.

    This is a convenience method that loads all meter data and returns
    a single 2D array of shape (total_timesteps, n_features). Use this
    only when the full dataset fits in RAM (~1GB for 50 meters × 30 days).

    For memory-constrained environments, use iter_meter_dataframes()
    and process meters individually.

    Args:
        data_directory: Path to the data directory.
        max_meters: Optional limit on meters to load.

    Returns:
        2D numpy array of shape (total_timesteps, n_features) with
        features in TRAINING_FEATURE_COLUMNS order.
    """
    all_feature_blocks: List[np.ndarray] = []
    total_rows: int = 0

    for meter_df in iter_meter_dataframes(data_directory, max_meters):
        # Extract only the feature columns as a numpy array.
        feature_block: np.ndarray = meter_df[TRAINING_FEATURE_COLUMNS].values
        all_feature_blocks.append(feature_block)
        total_rows += len(feature_block)

    # Vertically stack all meter feature arrays into one contiguous block.
    combined_features: np.ndarray = np.vstack(all_feature_blocks)

    loader_logger.info(
        "All features loaded and concatenated | total_rows=%d | shape=%s",
        total_rows,
        combined_features.shape,
    )

    return combined_features
